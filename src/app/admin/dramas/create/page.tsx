// ── Main Component ─────────────────────────────────────
export default function CreateDramaPage() {
  const [step, setStep] = useState(1);
  const [form, setForm] = useState<FormData>(INITIAL_FORM);
  const [categoryInput, setCategoryInput] = useState("");
  const [saving, setSaving] = useState(false);
  const [cancelingFlow, setCancelingFlow] = useState(false);
  const [stepError, setStepError] = useState<string | null>(null);
  const [activeUploadSessionId, setActiveUploadSessionId] = useState<string | null>(null);
  const [hasPendingUploadData, setHasPendingUploadData] = useState(false);
  const router = useRouter();
  const { toast } = useToast();
  const confirmDialog = useConfirm();
  const stepVideoCleanupRef = useRef<(() => Promise<boolean>) | null>(null);
  const publishLockRef = useRef(false);

  const navigateToDramaManagement = useCallback(() => {
    void router.replace("/admin/dramas");

    if (typeof window !== "undefined") {
      window.setTimeout(() => {
        if (window.location.pathname !== "/admin/dramas") {
          window.location.assign("/admin/dramas");
        }
      }, 200);
    }
  }, [router]);

  const validateStep = useCallback((stepNum: number): string | null => {
    if (stepNum === 1) {
      if (!form.verticalCover) return "Vertical cover is required.";
      if (!form.horizontalCover) return "Horizontal cover is required.";
      if (!form.dramaName.trim()) return "Drama name is required.";
      if (!form.synopsis.trim()) return "Synopsis is required.";
      if (form.categories.length === 0) return "At least one category is required.";
      return null;
    }

    if (stepNum === 2) {
      if (form.episodes.length === 0) return "Please upload at least one episode before continuing.";
      const invalidEpisode = form.episodes.find((episode) =>
        !episode.name.trim() ||
        !episode.videoUid ||
        episode.status !== "ready"
      );
      if (invalidEpisode) {
        if (!invalidEpisode.name.trim()) return "Every episode must have a name.";
        if (!invalidEpisode.videoUid) return "Every episode must have a valid uploaded video.";
        if (invalidEpisode.status === "failed") return "Some episodes failed processing. Please re-upload failed episodes.";
        return "Please wait until all episodes are processed and ready.";
      }
      return null;
    }

    if (stepNum === 3) {
      if (form.monetizationModel !== "free" && (!Number.isFinite(form.defaultPrice) || form.defaultPrice < 1)) {
        return "Default episode price must be at least 1 coin.";
      }
      if (form.monetizationModel === "partial") {
        if (!Number.isFinite(form.freeEpisodeCount) || form.freeEpisodeCount < 1) {
          return "Free episode count must be at least 1.";
        }
        if (form.freeEpisodeCount > form.episodes.length) {
          return "Free episode count cannot exceed total uploaded episodes.";
        }
      }
      return null;
    }

    if (stepNum === 4) {
      if (form.publishOption === "schedule" && !form.scheduleDate) {
        return "Please choose a schedule date and time.";
      }
      return null;
    }

    return null;
  }, [form]);

  const handlePublish = async (status: "published" | "draft") => {
    if (publishLockRef.current || saving) {
      return;
    }

    if (status === "published") {
      for (const stepNum of [1, 2, 3, 4]) {
        const error = validateStep(stepNum);
        if (error) {
          setStep(stepNum);
          setStepError(error);
          toast(error, "error");
          return;
        }
      }
    }

    publishLockRef.current = true;
    setStepError(null);
    setSaving(true);
    let publishSucceeded = false;
    try {
      const result = await adminApi.createDrama({
        title: form.dramaName,
        description: form.synopsis,
        dramaMode: form.dramaMode,
        isCompleted: form.dramaMode === "completed",
        categories: form.categories,
        regions: form.regions,
        tags: form.tags ? form.tags.split(",").map((t: string) => t.trim()) : [],
        status,
        cover: form.verticalCover || "",
        horizontalCover: form.horizontalCover || "",
        monetizationModel: form.monetizationModel,
        freeEpisodeCount: form.freeEpisodeCount,
        defaultPrice: form.defaultPrice,
        seoTitle: form.seoTitle,
        seoDescription: form.seoDescription,
        seoKeywords: form.seoKeywords,
        publishOption: form.publishOption,
        scheduleDate: form.scheduleDate,
        totalEpisodes: form.episodes.length,
        episodes: form.episodes.map((ep, idx) => ({
          episodeNumber: idx + 1,
          title: ep.name,
          duration: ep.duration ? parseDurationToSeconds(ep.duration) : 0,
          streamVideoId: ep.videoUid || "",
          thumbnail: ep.cover || "",
          subtitleUrl: ep.subtitleUrl || "",
          subtitleLanguage: ep.subtitleLanguage || "",
          isFree: form.monetizationModel === "free" || idx < form.freeEpisodeCount,
          unlockPrice: form.monetizationModel === "free" ? 0 : (ep.price ?? form.defaultPrice),
          status: ep.status === "ready" ? "Published" : "Processing",
        })),
      }) as any;

      const dramaId = result?.data?._id || result?._id;
      if (!dramaId) {
        throw new Error("Create drama succeeded but no drama id was returned.");
      }

      publishSucceeded = true;
      toast("Drama created successfully", "success");
      navigateToDramaManagement();
    } catch (err: any) {
      toast(err.message || "Failed to create drama", "error");
    } finally {
      if (!publishSucceeded) {
        publishLockRef.current = false;
        setSaving(false);
      }
    }
  };

  // Helper to parse "M:SS" or "MM:SS" duration string to seconds
  const parseDurationToSeconds = (dur: string): number => {
    const parts = dur.split(":").map(Number);
    if (parts.length === 2) return (parts[0] || 0) * 60 + (parts[1] || 0);
    if (parts.length === 3) return (parts[0] || 0) * 3600 + (parts[1] || 0) * 60 + (parts[2] || 0);
    return Number(dur) || 0;
  };

  const updateForm = useCallback(
    <K extends keyof FormData>(key: K, value: FormData[K]) => {
      setForm((prev) => ({ ...prev, [key]: value }));
    },
    []
  );

  const addCategory = () => {
    const val = categoryInput.trim();
    if (val && !form.categories.includes(val)) {
      updateForm("categories", [...form.categories, val]);
    }
    setCategoryInput("");
  };

  const removeCategory = (cat: string) => {
    updateForm(
      "categories",
      form.categories.filter((c) => c !== cat)
    );
  };

  const verticalCoverRef = useRef<HTMLInputElement>(null);
  const horizontalCoverRef = useRef<HTMLInputElement>(null);

  const triggerUpload = (field: "verticalCover" | "horizontalCover") => {
    const ref = field === "verticalCover" ? verticalCoverRef : horizontalCoverRef;
    ref.current?.click();
  };

  const [coverUploading, setCoverUploading] = useState<"verticalCover" | "horizontalCover" | null>(null);

  const handleFileChange = async (
    field: "verticalCover" | "horizontalCover",
    e: React.ChangeEvent<HTMLInputElement>
  ) => {
    const file = e.target.files?.[0];
    if (!file) return;
    e.target.value = "";

    // Show local preview immediately
    const previewUrl = URL.createObjectURL(file);
    updateForm(field, previewUrl);

    // Upload to R2
    setCoverUploading(field);
    try {
      const token = typeof window !== 'undefined' ? localStorage.getItem('admin_token') : null;
      const API_BASE = process.env.NEXT_PUBLIC_API_URL || 'https://api.tinytale.top';
      const formData = new FormData();
      formData.append('file', file);
      const res = await fetch(`${API_BASE}/api/admin/upload/image`, {
        method: 'POST',
        headers: token ? { 'Authorization': `Bearer ${token}` } : {},
        body: formData,
      });
      const result = await res.json();
      if (result.success && result.data?.url) {
        updateForm(field, result.data.url);
      } else {
        toast('Cover upload failed: ' + (result.error?.message || 'Unknown error'), 'error');
        updateForm(field, null);
      }
    } catch (err: any) {
      toast('Cover upload failed: ' + (err.message || 'Network error'), 'error');
      updateForm(field, null);
    } finally {
      URL.revokeObjectURL(previewUrl);
      setCoverUploading(null);
    }
  };

  const removeEpisode = async (id: string) => {
    const confirmed = await confirmDialog({
      title: "Delete Episode Card",
      message: "Are you sure you want to delete this episode card?",
      confirmText: "Delete",
      tone: "danger",
    });
    if (!confirmed) return;
    updateForm(
      "episodes",
      form.episodes.filter((e) => e.id !== id)
    );
  };

  const updateEpisode = (id: string, updates: Partial<Episode>) => {
    updateForm(
      "episodes",
      form.episodes.map((e) => (e.id === id ? { ...e, ...updates } : e))
    );
  };

  const nextStep = () => {
    const error = validateStep(step);
    if (error) {
      setStepError(error);
      toast(error, "error");
      return;
    }
    setStepError(null);
    setStep((s) => Math.min(4, s + 1));
  };

  const prevStep = () => {
    setStepError(null);
    setStep((s) => Math.max(1, s - 1));
  };

  useEffect(() => {
    setStepError(null);
  }, [step]);

  const handleCancelFlow = useCallback(async () => {
    if (cancelingFlow) return;
    setCancelingFlow(true);
    try {
      if (hasPendingUploadData || activeUploadSessionId) {
        let cleanupSuccess = true;
        if (stepVideoCleanupRef.current) {
          cleanupSuccess = await stepVideoCleanupRef.current();
        } else if (activeUploadSessionId) {
          await adminApi.cleanupUploadSession(activeUploadSessionId);
        }

        if (!cleanupSuccess) {
          return;
        }
      }

      router.push("/admin/dramas");
    } catch (err: any) {
      toast(err?.message || "Failed to cleanup uploaded Cloudflare data. Please retry.", "error");
    } finally {
      setCancelingFlow(false);
    }
  }, [activeUploadSessionId, cancelingFlow, hasPendingUploadData, router, toast]);

  return (
    <div className="min-h-screen bg-[#0f0f17] flex flex-col">
      {/* ── Sticky Header ── */}
      <header className="sticky top-0 z-50 border-b border-gray-800 bg-[#0f0f17]/95 backdrop-blur-sm">
        <div className="mx-auto flex h-16 max-w-5xl items-center justify-between px-6">
          <div className="flex items-center gap-3">
            <button
              type="button"
              onClick={() => void handleCancelFlow()}
              disabled={cancelingFlow}
              className="text-gray-400 hover:text-white transition-colors disabled:cursor-not-allowed disabled:opacity-50"
            >
              <ArrowLeftIcon />
            </button>
            <h1 className="text-lg font-semibold text-white">
              Create New Drama
            </h1>
          </div>
          <button type="button" onClick={() => void handlePublish("draft")} disabled={saving || !!coverUploading} className="text-sm text-indigo-400 hover:text-indigo-300 transition-colors disabled:opacity-50">
            {saving ? "Saving..." : coverUploading ? "Uploading cover..." : "Save as Draft"}
          </button>
        </div>
      </header>

      {/* ── Progress Stepper ── */}
      <div className="border-b border-gray-800 bg-[#0f0f17]">
        <div className="mx-auto max-w-5xl px-6 py-6">
          <div className="flex items-center justify-between">
            {STEPS.map((s, i) => (
              <div
                key={s.num}
                className="flex items-center flex-1 last:flex-none"
              >
                <div className="flex items-center gap-3">
                  <div
                    className={`flex h-9 w-9 items-center justify-center rounded-full text-sm font-semibold transition-colors ${
                      step > s.num
                        ? "bg-indigo-600 text-white"
                        : step === s.num
                        ? "bg-indigo-600 text-white"
                        : "border-2 border-gray-700 text-gray-500"
                    }`}
                  >
                    {step > s.num ? <CheckIcon /> : s.num}
                  </div>
                  <span
                    className={`text-sm font-medium whitespace-nowrap ${
                      step >= s.num ? "text-white" : "text-gray-500"
                    }`}
                  >
                    {s.label}
                  </span>
                </div>
                {i < STEPS.length - 1 && (
                  <div className="mx-4 h-px flex-1 bg-gray-800">
                    <div
                      className="h-full bg-indigo-600 transition-all"
                      style={{ width: step > s.num ? "100%" : "0%" }}
                    />
                  </div>
                )}
              </div>
            ))}
          </div>
        </div>
      </div>

      {/* ── Step Content ── */}
      <div className="flex-1 overflow-y-auto pb-24">
        <div className="mx-auto max-w-5xl px-6 py-8">
          {stepError && (
            <div className="mb-6 rounded-lg border border-red-700/50 bg-red-900/30 px-4 py-3 text-sm text-red-300">
              {stepError}
            </div>
          )}

          <div className={step === 1 ? "block" : "hidden"}>
            <StepBasicInfo
              form={form}
              updateForm={updateForm}
              categoryInput={categoryInput}
              setCategoryInput={setCategoryInput}
              addCategory={addCategory}
              removeCategory={removeCategory}
              triggerUpload={triggerUpload}
              handleFileChange={handleFileChange}
              verticalCoverRef={verticalCoverRef}
              horizontalCoverRef={horizontalCoverRef}
              coverUploading={coverUploading}
            />
          </div>
          <div className={step === 2 ? "block" : "hidden"}>
            <StepVideoSubtitles
              form={form}
              updateForm={updateForm}
              setForm={setForm}
              removeEpisode={removeEpisode}
              updateEpisode={updateEpisode}
              dramaTitle={form.dramaName}
              sharedUploadSessionId={activeUploadSessionId}
              onUploadSessionChange={setActiveUploadSessionId}
              onPendingUploadStateChange={setHasPendingUploadData}
              registerCleanupHandler={(cleanupHandler) => {
                stepVideoCleanupRef.current = cleanupHandler;
              }}
            />
          </div>
          <div className={step === 3 ? "block" : "hidden"}>
            <StepPayment
              form={form}
              updateForm={updateForm}
              updateEpisode={updateEpisode}
            />
          </div>
          <div className={step === 4 ? "block" : "hidden"}>
            <StepSeoPublish form={form} updateForm={updateForm} />
          </div>
        </div>
      </div>

      {/* ── Sticky Footer ── */}
      <footer className="sticky bottom-0 z-50 border-t border-gray-800 bg-[#0f0f17]/95 backdrop-blur-sm">
        <div className="mx-auto flex h-16 max-w-5xl items-center justify-between px-6">
          <button
            type="button"
            onClick={() => void handleCancelFlow()}
            disabled={cancelingFlow}
            className="rounded-lg border border-gray-700 px-5 py-2 text-sm font-medium text-gray-300 transition-colors hover:border-gray-500 hover:text-white disabled:cursor-not-allowed disabled:opacity-50"
          >
            {cancelingFlow ? "Canceling..." : "Cancel"}
          </button>
          <span className="text-sm text-gray-500">Step {step} of 4</span>
          <div className="flex items-center gap-3">
            {step > 1 && (
              <button
                type="button"
                onClick={prevStep}
                className="rounded-lg border border-gray-700 px-5 py-2 text-sm font-medium text-gray-300 transition-colors hover:border-gray-500 hover:text-white"
              >
                &larr; Previous
              </button>
            )}
            {step < 4 ? (
              <button
                type="button"
                onClick={nextStep}
                className="rounded-lg bg-indigo-600 px-5 py-2 text-sm font-medium text-white transition-colors hover:bg-indigo-700"
              >
                Next Step &rarr;
              </button>
            ) : (
              <button type="button" onClick={() => void handlePublish("published")} disabled={saving || !!coverUploading} className="rounded-lg bg-indigo-600 px-5 py-2 text-sm font-medium text-white transition-colors hover:bg-indigo-700 disabled:opacity-50">
                {saving ? "Publishing..." : coverUploading ? "Uploading cover..." : "Publish"}
              </button>
            )}
          </div>
        </div>
      </footer>
    </div>
  );
}

